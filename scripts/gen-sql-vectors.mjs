// Generates supabase/tests/01_vectors.test.sql from the shared Jest vectors so
// the SQL window math is checked against exactly the same expectations as
// src/domain/time.ts. Run: npm run gen:sql-vectors
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const v = JSON.parse(readFileSync(join(root, 'src/domain/__tests__/vectors.json'), 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const lines = [];
const count = v.windows.length * 2 + v.planDayAt.length + v.startDate.length;
lines.push('-- GENERATED by scripts/gen-sql-vectors.mjs from src/domain/__tests__/vectors.json.');
lines.push('-- Do not edit by hand.');
lines.push('begin;');
lines.push(`select plan(${count});`);
lines.push('');
for (const w of v.windows) {
  const call = `public.plan_window(${q(w.day)}::date, ${q(w.sleep)}::time, ${q(w.tz)})`;
  lines.push(
    `select is((${call}).open_at, ${q(w.open)}::timestamptz, ${q(`window open: ${w.name}`)});`,
  );
  lines.push(
    `select is((${call}).close_at, ${q(w.close)}::timestamptz, ${q(`window close: ${w.name}`)});`,
  );
}
lines.push('');
for (const p of v.planDayAt) {
  const expected = p.day === null ? 'null::date' : `${q(p.day)}::date`;
  lines.push(
    `select is(private.plan_day_at(${q(p.at)}::timestamptz, ${q(p.sleep)}::time, ${q(p.tz)}), ${expected}, ${q(`plan_day_at ${p.tz} ${p.sleep} @ ${p.at}`)});`,
  );
}
lines.push('');
for (const s of v.startDate) {
  lines.push(
    `select is(private.start_date_for(${q(s.createdAt)}::timestamptz, ${q(s.sleep)}::time, ${q(s.tz)}), ${q(s.start)}::date, ${q(`start_date_for ${s.tz} ${s.sleep} @ ${s.createdAt}`)});`,
  );
}
lines.push('');
lines.push('select * from finish();');
lines.push('rollback;');
writeFileSync(join(root, 'supabase/tests/01_vectors.test.sql'), lines.join('\n') + '\n');
console.log(`wrote ${count} assertions`);
